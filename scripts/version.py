import re
import sys
from pathlib import Path

match = re.findall(r'^version:\s*([0-9]+\.[0-9]+\.[0-9]+)\+([1-9][0-9]*)\s*$', Path('pubspec.yaml').read_text(), re.M)
if len(match) != 1:
    raise SystemExit('Expected one SemVer+build in pubspec.yaml')
version, build = match[0]
if len(sys.argv) == 2 and sys.argv[1] in ('version', 'build'):
    print(version if sys.argv[1] == 'version' else build)
elif len(sys.argv) == 2 and sys.argv[1] in ('generate', 'check'):
    p = Path('lib/app/version.dart')
    value = f"// Generated by scripts/version.py from pubspec.yaml.\nconst appVersion = '{version}';\nconst appBuild = '{build}';\n"
    if sys.argv[1] == 'generate':
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(value)
    elif p.read_text() != value:
        raise SystemExit('Generated version is stale')
else:
    raise SystemExit('Use version, build, generate or check')
